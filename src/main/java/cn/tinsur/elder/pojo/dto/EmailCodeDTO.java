package cn.tinsur.elder.pojo.dto;

import lombok.Data;

/**
 * 邮箱验证码相关DTO：
 * 发送验证码时用到 scene 和 email（绑定邮箱、更换邮箱验证新邮箱场景需要传email，其余场景发到当前用户绑定邮箱）；
 * 绑定邮箱提交时用到 code 和 email；更换邮箱提交时用到 code（旧邮箱验证码）和 newCode（新邮箱验证码）
 */
@Data
public class EmailCodeDTO {

    /**
     * 使用场景：BIND_EMAIL绑定邮箱 CHANGE_PASSWORD邮箱改密 CHANGE_EMAIL更换邮箱 CHANGE_EMAIL_NEW更换邮箱时验证新邮箱
     */
    private String scene;

    /**
     * 邮箱（发送时为接收验证码的邮箱，绑定时为待绑定的邮箱）
     */
    private String email;

    /**
     * 用户填写的验证码（绑定邮箱、邮箱改密、更换邮箱时为旧邮箱收到的验证码）
     */
    private String code;

    /**
     * 用户填写的新邮箱验证码（仅更换邮箱场景使用，验证码发到待更换的新邮箱）
     */
    private String newCode;
}